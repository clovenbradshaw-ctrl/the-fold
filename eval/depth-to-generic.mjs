// eval/depth-to-generic.mjs — does the LEVEL a question is asked at read off
// the number of recall hops before it goes generic, on restatements NOT
// hand-built to hit each level cleanly?
//
//   node eval/depth-to-generic.mjs [--n-per-level N] [--max-hops H]
//
// The claim under test (reported informally elsewhere, not yet run against
// labelled data): L0 (a single event) settles further into the field before
// its top match falls into the field's own null band than L1 (a person's
// character), which goes further than L2 (a relation between two beings),
// which goes about as far as L3 (an abstract theme) — a monotone ordering,
// with NO model call needed to read the level off a restatement once it is
// in hand.
//
// WHAT "LABELLED" MEANS HERE, and why it matters (this is the gap named
// against the earlier, hand-built four-probe version): each restatement is
// generated by a real model call that DECLARES the level it is asked to
// write at — the label is assigned by what was asked for, never by
// inspecting the hop count afterward, and never by hand-picking which
// restatement to keep. Several restatements per level, about DIFFERENT real
// events in the corpus, not four versions of one topic. If the level still
// separates on a set built this way, the earlier finding generalizes; if it
// does not, that is the finding.
//
// THE NULL (II.23: a control built to fail before a result is trusted): the
// same hop-to-generic measurements, with the LEVEL LABELS SHUFFLED across
// the same restatements. If shuffling the labels does not destroy whatever
// separation is found, the separation was never about level.
//
// Uses relative.js's real Field/recallAgainstNull, unmodified in its
// public behavior — only steps/spread were added as additive options
// (2026-09-08) so a hop-N recall can be checked against a hop-N band
// instead of the field's own default (hop 1).
import { readFileSync } from "node:fs";
import { Field, tokensOf, isWord } from "../relative.js";

const args = process.argv.slice(2);
const flag = (name, dflt) => { const i = args.indexOf(`--${name}`); return i >= 0 ? Number(args[i + 1]) : dflt; };
const N_PER_LEVEL = flag("n-per-level", 5);
const MAX_HOPS = flag("max-hops", 8);
const DRAWS = flag("draws", 120);
const SEED = flag("seed", 11);
let s = SEED; const rng = () => { s = (s * 1103515245 + 12345) & 0x7fffffff; return s / 0x7fffffff; };

const FIXTURE = new URL("../../eoreader7/native/eval/the-fold/fixtures/tolstoy-borodino.txt", import.meta.url).pathname;
const raw = readFileSync(FIXTURE, "utf8");
const NAME = "tolstoy";
const paras = raw.split(/\n\s*\n/).map((p) => p.replace(/\s+/g, " ").trim()).filter((p) => tokensOf(p).filter(isWord).length >= 8);
const source = paras.join("\n\n");

const field = new Field();
for (const p of paras) field.admit(p, { source: NAME });
console.log(`corpus: ${paras.length} passages, ${source.length.toLocaleString()} bytes; field of ${field.size} nodes, vocabulary ${field.vocab.size}`);

// Real seed events, at real positions across the whole corpus (not
// clustered), each the basis for ONE restatement — never four versions of
// the same passage, so a level's separation cannot be "this one topic is
// just easier."
const SEED_INDICES = [4, 55, 100, 150, 200, 237, 280, 300, 350, 400, 450, 500, 550, 600, 650, 700, 720, 30, 80, 170];
const seeds = SEED_INDICES.filter((i) => i < paras.length).map((i) => paras[i]);

const LEVELS = ["L0-event", "L1-person", "L2-relation", "L3-theme"];
const PROMPTS = {
  "L0-event": (p) => `Read this passage from a novel:\n\n"${p}"\n\nIn one sentence, state the single specific thing that happens in it — one concrete act, nothing more. Do not name the book or the author. Do not explain.`,
  "L1-person": (p) => `Read this passage from a novel:\n\n"${p}"\n\nIn one or two sentences, describe the character or temperament of the main person in this passage — what kind of person they are, not what happens here. Do not name the book or the author. Do not explain.`,
  "L2-relation": (p) => `Read this passage from a novel:\n\n"${p}"\n\nIn one or two sentences, describe the relationship between two people connected in or around this passage — how they stand toward each other. If the passage does not clearly involve two people, describe the relationship it implies or gestures at. Do not name the book or the author. Do not explain.`,
  "L3-theme": (p) => `Read this passage from a novel:\n\n"${p}"\n\nIn one sentence, name the abstract theme or idea this passage is an instance of — something the passage is ABOUT at the level of an idea, not what literally happens. Do not name the book or the author. Do not explain.`,
};

async function ask(prompt) {
  const res = await fetch("http://localhost:11434/api/chat", {
    method: "POST",
    body: JSON.stringify({ model: "gemma2:2b", messages: [{ role: "user", content: prompt }], stream: false, options: { temperature: 0.4, seed: SEED } }),
  });
  const j = await res.json();
  return String(j.message?.content ?? "").trim().replace(/^["“]|["”]$/g, "");
}

/** Sweep hops 1..maxHops; the first hop whose verdict is not "figure" is where it goes generic. null = never went generic within maxHops. */
function depthToGeneric(cue, { maxHops = MAX_HOPS, draws = DRAWS } = {}) {
  const trace = [];
  let generic = null;
  for (let h = 1; h <= maxHops; h++) {
    const r = field.recallAgainstNull(cue, { steps: h, draws });
    trace.push({ hop: h, kind: r.kind, activation: r.top?.activation ?? 0, bandHi: r.band.hi, margin: r.band.margin });
    if (r.kind !== "figure" && generic === null) generic = h;
  }
  return { generic, hop1Figure: trace[0]?.kind === "figure", trace };
}

const items = [];
console.log(`\ngenerating ${N_PER_LEVEL} restatements per level, ${LEVELS.length * N_PER_LEVEL} real model calls (gemma2:2b)…`);
let seedIdx = 0;
for (const level of LEVELS) {
  for (let k = 0; k < N_PER_LEVEL; k++) {
    const seed = seeds[seedIdx % seeds.length]; seedIdx++;
    const t0 = Date.now();
    let text;
    try { text = await ask(PROMPTS[level](seed)); }
    catch (e) { console.log(`  ${level} #${k}: MODEL CALL FAILED — ${e.message}`); continue; }
    const ms = Date.now() - t0;
    items.push({ level, seed, text });
    console.log(`  ${level} #${k} (${ms}ms): "${text.slice(0, 100)}${text.length > 100 ? "…" : ""}"`);
  }
}

console.log(`\n${items.length} restatements generated. Measuring depth-to-generic for each (pure, no model)…`);
for (const it of items) {
  it.result = depthToGeneric(it.text);
}

console.log("\n— depth-to-generic, by declared level (never inferred from the hop count) —");
console.log("  level          n   hop1=figure   mean depth-to-generic (of those that went generic)   never-generic");
const byLevel = new Map();
for (const it of items) { if (!byLevel.has(it.level)) byLevel.set(it.level, []); byLevel.get(it.level).push(it); }
const meanDepth = (rows) => { const gen = rows.filter((r) => r.result.generic != null).map((r) => r.result.generic); return gen.length ? gen.reduce((a, b) => a + b, 0) / gen.length : null; };
for (const level of LEVELS) {
  const rows = byLevel.get(level) ?? [];
  const hop1 = rows.filter((r) => r.result.hop1Figure).length;
  const never = rows.filter((r) => r.result.generic == null).length;
  const md = meanDepth(rows);
  console.log(`  ${level.padEnd(14)}${String(rows.length).padStart(2)}   ${String(hop1).padStart(3)}/${rows.length}         ${md == null ? "  n/a" : md.toFixed(2).padStart(6)}                                              ${never}/${rows.length}`);
}

// Monotone check: is L0's mean depth >= L1's >= L2's >= L3's (allowing ties)?
const means = LEVELS.map((l) => meanDepth(byLevel.get(l) ?? []));
const monotone = means.every((m, i) => i === 0 || m == null || means[i - 1] == null || m <= means[i - 1]);
console.log(`\nmonotone (L0 >= L1 >= L2 >= L3, ties allowed): ${monotone}`);
console.log(`means: ${LEVELS.map((l, i) => `${l}=${means[i] == null ? "n/a" : means[i].toFixed(2)}`).join("  ")}`);

// THE NULL: shuffle the level labels across the same items, same trace data
// (already computed — this reuses the measurement, never re-runs recall),
// and check whether the SAME monotone pattern still shows up by chance.
console.log("\n— the null: the same measurements with level labels shuffled —");
function shuffledMeans(itemsIn) {
  const labels = itemsIn.map((it) => it.level);
  for (let i = labels.length - 1; i > 0; i--) { const j = Math.floor(rng() * (i + 1)); [labels[i], labels[j]] = [labels[j], labels[i]]; }
  const shuffled = itemsIn.map((it, i) => ({ ...it, level: labels[i] }));
  const byL = new Map();
  for (const it of shuffled) { if (!byL.has(it.level)) byL.set(it.level, []); byL.get(it.level).push(it); }
  return LEVELS.map((l) => meanDepth(byL.get(l) ?? []));
}
const DRAWS_NULL = 200;
let monotoneByChance = 0;
for (let d = 0; d < DRAWS_NULL; d++) {
  const m = shuffledMeans(items);
  const mono = m.every((v, i) => i === 0 || v == null || m[i - 1] == null || v <= m[i - 1]);
  if (mono) monotoneByChance++;
}
console.log(`  a fully monotone L0>=L1>=L2>=L3 ordering, by chance, in ${DRAWS_NULL} label-shuffles: ${monotoneByChance}/${DRAWS_NULL}`);
console.log(`  (a monotone chain among 4 groups by pure chance is inherently not rare with only 4! = 24 orderings —`);
console.log(`   this null states exactly how rare, on THESE measurements, rather than assuming it)`);

console.log("\n— per-item detail —");
for (const it of items) console.log(`  ${it.level.padEnd(14)} generic@${String(it.result.generic ?? "never").padEnd(6)} hop1=${it.result.hop1Figure ? "figure" : it.result.trace[0].kind}  "${it.text.slice(0, 70)}"`);
